import { exists, writeFile } from "node:fs/promises";

import type { Paths } from "../constants";
import { ok, type Result } from "../types";
import { readWorkspaceConfig } from "./config";

export interface GenerateAgentFilesResult {
  agentsMd: "created" | "exists";
  mcpJson: "created" | "exists";
}

const WORKSPACE_AGENT_BOOTSTRAP_SHIM = `# Generated by grove - do not edit manually

Grove workspace. Instruction context is served on demand: call the \`context_touch\` MCP tool (or \`grove ws context touch <paths>\`) for the paths you work on.
`;

const WORKSPACE_MCP_JSON = `${JSON.stringify(
  { mcpServers: { grove: { command: "grove", args: ["mcp", "connect"] } } },
  null,
  2,
)}\n`;

async function ensureWorkspaceEntryFile(
  filePath: string,
  content: string,
): Promise<"created" | "exists"> {
  if (await exists(filePath)) {
    return "exists";
  }

  await writeFile(filePath, content);
  return "created";
}

export async function generateAgentFiles(
  workspace: string,
  paths: Paths,
): Promise<Result<GenerateAgentFilesResult>> {
  const configResult = await readWorkspaceConfig(workspace, paths);
  if (!configResult.ok) {
    return configResult;
  }

  const agentsMdStatus = await ensureWorkspaceEntryFile(
    paths.agentsMd(workspace),
    WORKSPACE_AGENT_BOOTSTRAP_SHIM,
  );
  const mcpJsonStatus = await ensureWorkspaceEntryFile(
    paths.mcpJson(workspace),
    WORKSPACE_MCP_JSON,
  );

  return ok({
    agentsMd: agentsMdStatus,
    mcpJson: mcpJsonStatus,
  });
}
