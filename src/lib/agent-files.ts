import { exists, mkdir, writeFile } from "node:fs/promises";

import type { Paths } from "../constants";
import { err, ok, type Result } from "../types";
import { readWorkspaceConfig } from "./config";

export interface GenerateAgentFilesResult {
  agentsMd: "created" | "exists";
  mcpJson: "created" | "exists";
  opencodeJson: "created" | "exists";
  antigravityMcpPlugin: "created" | "exists";
  antigravityMcpConfig: "created" | "exists";
}

const WORKSPACE_AGENT_BOOTSTRAP_SHIM = `# Generated by grove - do not edit manually

Grove workspace. Instruction context is served on demand: call the \`context_touch\` MCP tool (or \`grove ws context touch <paths>\`) for the paths you work on.
`;

const WORKSPACE_MCP_JSON = `${JSON.stringify(
  { mcpServers: { grove: { command: "grove", args: ["mcp", "connect"] } } },
  null,
  2,
)}\n`;

const WORKSPACE_ANTIGRAVITY_PLUGIN_JSON = `${JSON.stringify({ name: "grove-mcp" }, null, 2)}\n`;

function buildAntigravityMcpConfig(workspace: string): string {
  return `${JSON.stringify(
    {
      mcpServers: {
        grove: { command: "grove", args: ["mcp", "connect", "--workspace", workspace] },
      },
    },
    null,
    2,
  )}\n`;
}

function buildOpenCodeConfig(workspace: string): string {
  return `${JSON.stringify(
    {
      $schema: "https://opencode.ai/config.json",
      mcp: {
        grove: {
          type: "local",
          command: ["grove", "mcp", "connect", "--workspace", workspace],
          enabled: true,
        },
      },
    },
    null,
    2,
  )}\n`;
}

async function ensureWorkspaceEntryFile(
  filePath: string,
  content: string,
): Promise<"created" | "exists"> {
  if (await exists(filePath)) {
    return "exists";
  }

  await writeFile(filePath, content);
  return "created";
}

export async function generateAgentFiles(
  workspace: string,
  paths: Paths,
): Promise<Result<GenerateAgentFilesResult>> {
  const configResult = await readWorkspaceConfig(workspace, paths);
  if (!configResult.ok) {
    return configResult;
  }

  try {
    const agentsMdStatus = await ensureWorkspaceEntryFile(
      paths.agentsMd(workspace),
      WORKSPACE_AGENT_BOOTSTRAP_SHIM,
    );
    const mcpJsonStatus = await ensureWorkspaceEntryFile(
      paths.mcpJson(workspace),
      WORKSPACE_MCP_JSON,
    );
    const opencodeJsonStatus = await ensureWorkspaceEntryFile(
      paths.opencodeJson(workspace),
      buildOpenCodeConfig(workspace),
    );

    await mkdir(paths.antigravityMcpPluginDir(workspace), { recursive: true });
    const antigravityMcpPluginStatus = await ensureWorkspaceEntryFile(
      paths.antigravityMcpPluginManifest(workspace),
      WORKSPACE_ANTIGRAVITY_PLUGIN_JSON,
    );
    const antigravityMcpConfigStatus = await ensureWorkspaceEntryFile(
      paths.antigravityMcpConfig(workspace),
      buildAntigravityMcpConfig(workspace),
    );

    return ok({
      agentsMd: agentsMdStatus,
      mcpJson: mcpJsonStatus,
      opencodeJson: opencodeJsonStatus,
      antigravityMcpPlugin: antigravityMcpPluginStatus,
      antigravityMcpConfig: antigravityMcpConfigStatus,
    });
  } catch (e) {
    return err(
      `Failed to write workspace agent files: ${e instanceof Error ? e.message : String(e)}`,
      "AGENT_FILES_WRITE_FAILED",
    );
  }
}
