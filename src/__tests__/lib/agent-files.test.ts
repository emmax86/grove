import { afterEach, beforeEach, describe, expect, it } from "bun:test";
import { exists, mkdir, readFile, symlink, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { createPaths } from "../../constants";
import { generateAgentFiles } from "../../lib/agent-files";
import { writeConfig } from "../../lib/config";
import { cleanup, createTestDir, createTestGitRepo } from "../helpers";

const WORKSPACE_AGENT_BOOTSTRAP_SHIM = `# Generated by grove - do not edit manually

Grove workspace. Instruction context is served on demand: call the \`context_touch\` MCP tool (or \`grove ws context touch <paths>\`) for the paths you work on.
`;

describe("generateAgentFiles", () => {
  let tempDir: string;
  let paths: ReturnType<typeof createPaths>;

  beforeEach(async () => {
    tempDir = await createTestDir();
    paths = createPaths(join(tempDir, "workspaces"));
  });

  afterEach(() => cleanup(tempDir));

  function expectWorkspaceBootstrapShim(content: string) {
    expect(content).toBe(WORKSPACE_AGENT_BOOTSTRAP_SHIM);
    expect(Array.from(content).every((char) => char.charCodeAt(0) <= 127)).toBe(true);
  }

  /** Create workspace dir, .claude dir, and workspace.json */
  async function setupWorkspace(ws: string, repos: { name: string; path: string }[] = []) {
    await mkdir(paths.workspace(ws), { recursive: true });
    await mkdir(paths.workspaceClaudeDir(ws), { recursive: true });
    await writeConfig(paths.workspaceConfig(ws), { name: ws, repos });
  }

  /**
   * Create a real git repo, wire up trees/{repo}/{slug} symlink,
   * and optionally write a CLAUDE.md into the repo.
   */
  async function setupRepo(
    ws: string,
    name: string,
    opts: { defaultBranch?: string; hasClaude?: boolean } = {},
  ): Promise<string> {
    const { defaultBranch = "main", hasClaude = true } = opts;
    const repoPath = await createTestGitRepo(tempDir, name, defaultBranch);

    // Create trees/{repo}/ dir and symlink trees/{repo}/{slug} -> repo
    const repoDir = paths.repoDir(ws, name);
    await mkdir(repoDir, { recursive: true });
    const slug = defaultBranch.replaceAll("/", "-");
    await symlink(repoPath, paths.worktreeDir(ws, name, slug));

    if (hasClaude) {
      await writeFile(join(repoPath, "CLAUDE.md"), `# ${name}\nProject docs.\n`);
    }

    return repoPath;
  }

  // ── workspace entry files ───────────────────────────────────────

  describe("workspace entry files", () => {
    it("does not create CLAUDE.md, which would shadow AGENTS.md in Claude Code", async () => {
      await setupWorkspace("ws");

      const result = await generateAgentFiles("ws", paths);
      expect(result.ok).toBe(true);

      expect(await exists(join(paths.workspace("ws"), "CLAUDE.md"))).toBe(false);
    });

    it("does not write .claude/trees.md", async () => {
      const pathA = await setupRepo("ws", "alpha");
      await setupWorkspace("ws", [{ name: "alpha", path: pathA }]);

      const result = await generateAgentFiles("ws", paths);
      expect(result.ok).toBe(true);

      expect(await exists(join(paths.workspace("ws"), ".claude", "trees.md"))).toBe(false);
    });

    it("leaves an existing CLAUDE.md untouched", async () => {
      await setupWorkspace("ws");
      const claudeMd = join(paths.workspace("ws"), "CLAUDE.md");
      await writeFile(claudeMd, "# My custom workspace notes\n");

      const result = await generateAgentFiles("ws", paths);
      expect(result.ok).toBe(true);

      expect(await readFile(claudeMd, "utf-8")).toBe("# My custom workspace notes\n");
    });

    it("new-workspace shim is the two-line touch pointer", async () => {
      await setupWorkspace("ws");

      const result = await generateAgentFiles("ws", paths);
      expect(result.ok).toBe(true);
      if (!result.ok) {
        return;
      }

      const shim = await readFile(paths.agentsMd("ws"), "utf-8");
      expect(shim).toContain("context_touch");
      expect(shim).toContain("grove ws context touch");
      expect(shim.split("\n").filter((l) => l.trim()).length).toBeLessThanOrEqual(4);
    });

    it("is idempotent", async () => {
      await setupWorkspace("ws");

      const result1 = await generateAgentFiles("ws", paths);
      expect(result1.ok).toBe(true);
      const agentsMd1 = await readFile(paths.agentsMd("ws"), "utf-8");

      const result2 = await generateAgentFiles("ws", paths);
      expect(result2.ok).toBe(true);
      const agentsMd2 = await readFile(paths.agentsMd("ws"), "utf-8");

      expect(agentsMd1).toBe(agentsMd2);
    });
  });

  describe("AGENTS.md creation", () => {
    it("creates AGENTS.md when it does not exist", async () => {
      await setupWorkspace("ws");

      const result = await generateAgentFiles("ws", paths);
      expect(result.ok).toBe(true);
      if (!result.ok) {
        return;
      }

      expect(result.value.agentsMd).toBe("created");

      const content = await readFile(paths.agentsMd("ws"), "utf-8");
      expectWorkspaceBootstrapShim(content);
    });

    it("does not overwrite existing AGENTS.md", async () => {
      await setupWorkspace("ws");
      await writeFile(paths.agentsMd("ws"), "# My custom Codex notes\n@.claude/trees.md\n");

      const result = await generateAgentFiles("ws", paths);
      expect(result.ok).toBe(true);
      if (!result.ok) {
        return;
      }

      expect(result.value.agentsMd).toBe("exists");

      const content = await readFile(paths.agentsMd("ws"), "utf-8");
      expect(content).toBe("# My custom Codex notes\n@.claude/trees.md\n");
    });
  });

  // ── .mcp.json generation ─────────────────────────────────────────

  describe(".mcp.json generation", () => {
    it("generates .mcp.json pointing at the grove bridge", async () => {
      await setupWorkspace("ws");

      const result = await generateAgentFiles("ws", paths);
      expect(result.ok).toBe(true);
      if (!result.ok) {
        return;
      }

      expect(result.value.mcpJson).toBe("created");
      const config = JSON.parse(await readFile(paths.mcpJson("ws"), "utf-8"));
      expect(config.mcpServers.grove).toEqual({ command: "grove", args: ["mcp", "connect"] });
    });

    it("does not overwrite a user-modified .mcp.json", async () => {
      await setupWorkspace("ws");
      await writeFile(paths.mcpJson("ws"), `{"mcpServers":{}}`);

      const result = await generateAgentFiles("ws", paths);
      expect(result.ok).toBe(true);
      if (!result.ok) {
        return;
      }

      expect(result.value.mcpJson).toBe("exists");
      const content = await readFile(paths.mcpJson("ws"), "utf-8");
      expect(content).toBe(`{"mcpServers":{}}`);
    });
  });

  // ── error handling ──────────────────────────────────────────────

  describe("error handling", () => {
    it("returns WORKSPACE_NOT_FOUND for non-existent workspace", async () => {
      const result = await generateAgentFiles("ghost", paths);
      expect(result.ok).toBe(false);
      if (!result.ok) {
        expect(result.code).toBe("WORKSPACE_NOT_FOUND");
      }
    });
  });
});
